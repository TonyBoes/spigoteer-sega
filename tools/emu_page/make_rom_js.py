#!/usr/bin/env python3
"""Write rom.js for the browser quick-test page.

    python3 tools/emu_page/make_rom_js.py ROM.gb OUT/rom.js --label "main a39c7d3 unlocked"

rom.js sets two globals the page reads: ROM_B64 (the ROM, base64) and
ROM_LABEL (the "ROM: ..." line shown on the page).
"""
import argparse
import base64
import hashlib


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rom")
    ap.add_argument("out")
    ap.add_argument("--label", default="", help="build/commit text shown on the page")
    a = ap.parse_args()
    data = open(a.rom, "rb").read()
    sha = hashlib.sha1(data).hexdigest()[:10]
    label = (a.label + " " if a.label else "") + "(sha1 " + sha + ", %d KB)" % (len(data) // 1024)
    with open(a.out, "w") as f:
        f.write("// generated by tools/emu_page/make_rom_js.py; do not edit\n")
        f.write("var ROM_LABEL = %s;\n" % repr(label).replace("'", '"'))
        f.write('var ROM_B64 = "%s";\n' % base64.b64encode(data).decode())
    print("wrote", a.out, label)


main()
