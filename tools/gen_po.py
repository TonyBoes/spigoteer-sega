#!/usr/bin/env python3
"""The Pour-Off's art (src/po.c, docs/minigames_bosses.md section 5) -> build/po_art.h (src/po.c's bank), build/po.json
(tests) and the x8 preview out/preview/po_dregs_x8.png.

  assets/art/pouroff/bigwig.txt  BG: the clown (BIGWIG v2), a Pour-Off-only crowd look: 12 tiles as a patron look in src/po.c (shift-0 pose
                               4, the blank pair 2, the 2 px sway pose 6), colours assets/palettes.json pouroff_bigwig.
  assets/art/dregs/dregs.txt   OBJ: Dregs, the rival bartender, 5 pictures 16x24 as Sal's (idle, walk1, walk2, fill, fail)
                               (idle, walk1, walk2, fill, slide, catch, fail), 8 tiles a frame like bartender.txt.
                               PROPOSAL, pending owner approval (the file's first line says so; this tool checks it).

Usage: gen_po.py outdir previewdir
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_art import blocks, check_holes, png, tile_bytes  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
HEADER = "; Art: APPROVED by the owner 2026-10-29"


def main():
    outdir, prev = Path(sys.argv[1]), Path(sys.argv[2])
    outdir.mkdir(parents=True, exist_ok=True)
    prev.mkdir(parents=True, exist_ok=True)
    path = ROOT / "assets/art/dregs/dregs.txt"
    if not path.read_text().startswith(HEADER):
        sys.exit(f"gen_po: {path.name}: the first line must start with '{HEADER}'")
    frames = [r for _, r in blocks(path)]
    if len(frames) != 5 or not all(len(f) == 24 and all(len(r) == 16 and set(r) <= set(".-+#") for r in f) for f in frames):
        sys.exit("gen_po: dregs.txt needs 5 frames of 16x24 in . - + #")
    tiles, padded = [], []
    for f in frames:
        pad = list(f) + ["." * 16] * 8                  # 16x32 with a transparent pad, as the Spigoteer's
        padded.append(pad)
        for ty in (0, 16):                              # the top entry row, the bottom one (entries c0 top, c1 top, c0 bottom, c1 bottom)
            for cx in (0, 8):
                tiles += tile_bytes(pad, cx, ty) + tile_bytes(pad, cx, ty + 8)
    n = len(tiles) // 16
    clown = [r for _, r in blocks(ROOT / "assets/art/pouroff/bigwig.txt")]
    if len(clown) != 1 or len(clown[0]) != 16 or not all(len(r) == 16 and set(r) <= set(".-+#") for r in clown[0]):
        sys.exit("gen_po: bigwig.txt needs one 16x16 figure in . - + #")
    check_holes("pouroff", "front", 0, clown[0])
    c0 = [r + "." * 8 for r in clown[0]]                  # shift 0 in the 24x16 footprint (the 3rd column is the shared blank pair)
    c2 = ["." * 2 + r + "." * 6 for r in clown[0]]        # the sway pose, 2 px right
    ctiles = []
    for tx in (0, 8):
        ctiles += tile_bytes(c0, tx, 0) + tile_bytes(c0, tx, 8)
    ctiles += tile_bytes(["." * 8] * 8, 0, 0) * 2
    for tx in (0, 8, 16):
        ctiles += tile_bytes(c2, tx, 0) + tile_bytes(c2, tx, 8)
    assert len(ctiles) == 12 * 16
    lines = [
        "// generated by tools/gen_po.py from assets/art/dregs/dregs.txt -- do not edit; #included by src/po.c",
        f"#define PO_DREGS_TILES {n}   // OBJ tiles: 5 pictures x 8 (idle, walk1, walk2, fill, fail), as Sal's; src/po.c maps the 7 logical states with BT_PIC",
        "static const uint8_t po_dregs_tiles[%d] = { %s };" % (len(tiles), ", ".join(f"0x{b:02X}" for b in tiles)),
        "// the clown (assets/art/pouroff/bigwig.txt): one crowd look's 12 BG tiles, in the order of a patron look's po.c pose: shift 0 (2 columns x 2), the blank pair, shift 2 (3 x 2)",
        "static const uint8_t po_clown_tiles[192] = { %s };" % ", ".join(f"0x{b:02X}" for b in ctiles), ""]
    (outdir / "po_art.h").write_text("\n".join(lines))
    (outdir / "po.json").write_text(json.dumps({"dregs": tiles, "n": n, "clown": ctiles}))
    png(padded, prev / "po_dregs_x8.png", 8, transparent=True)
    png([c0, c2], prev / "po_clown_x8.png", 8)
    print(f"gen_po: Dregs {n} OBJ tiles")


if __name__ == "__main__":
    main()
