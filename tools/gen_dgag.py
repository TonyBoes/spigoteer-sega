#!/usr/bin/env python3
"""Dregs's late-arrival gags' art (src/dgag.c, docs/story.md running gag 1; design in docs/story.md "Dregs's exits") ->
build/dgag_art.h (src/dgag.c's bank), build/dgag.json (tests) and the x8 sheet out/preview/dgag_x8.png.

  assets/art/dregs/dregs.txt     existing (Pour-Off, PROPOSAL): frame 0 (upright) and 5 (reaching arm), 16x24 in the Spigoteer's layout
  assets/art/monkey/monkey.txt   existing (approved): frames 1, 2, the running monkey
  assets/art/dust.txt            existing (approved): the dust puff, 3 frames of 8x16
  assets/art/dgag/*.txt          new PROPOSALS (first line says so): lying 24x16, ball 16x16, boots, hat, plate, arc, crate, saucer, beam, cooler, soda

All OBJ in 8x16 entries stored column by column (top tile, bottom tile), like the Spigoteer's.
Usage: gen_dgag.py outdir previewdir
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_art import blocks, png, tile_bytes  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
HEADER = "; Art: PROPOSAL (new, unapproved: pending owner approval)"
OK = set(".-+#")


def grab(path, n, w, h, header=None):
    path = Path(path)
    if header and not path.read_text().startswith(header):
        sys.exit(f"gen_dgag: {path.name}: the first line must start with '{header}'")
    fr = [r for _, r in blocks(path)]
    if len(fr) < n or not all(len(f) == h and all(len(r) == w and set(r) <= OK for r in f) for f in fr):
        sys.exit(f"gen_dgag: {path.name}: needs frames of {w}x{h} in . - + # (at least {n})")
    return fr


def entries(frame, w):
    """a 16/24-wide, 16-high frame -> columns of 8x16 entries: top tile, bottom tile."""
    t = []
    for cx in range(0, w, 8):
        t += tile_bytes(frame, cx, 0) + tile_bytes(frame, cx, 8)
    return t


def bartender_layout(frame24):
    pad = list(frame24) + ["." * 16] * 8                # 16x32: entries c0 top, c1 top, c0 bottom, c1 bottom
    t = []
    for ty in (0, 16):
        for cx in (0, 8):
            t += tile_bytes(pad, cx, ty) + tile_bytes(pad, cx, ty + 8)
    return t


def pair(art8):
    """an 8x8 picture -> one 8x16 entry: the picture on top, an empty tile under it."""
    return tile_bytes(art8, 0, 0) + tile_bytes(["." * 8] * 8, 0, 0)


def main():
    outdir, prev = Path(sys.argv[1]), Path(sys.argv[2])
    outdir.mkdir(parents=True, exist_ok=True)
    prev.mkdir(parents=True, exist_ok=True)
    dg = ROOT / "assets/art/dgag"
    dregs = grab(ROOT / "assets/art/dregs/dregs.txt", 7, 16, 24)
    monkey = grab(ROOT / "assets/art/monkey/monkey.txt", 3, 16, 16)
    dust = grab(ROOT / "assets/art/dust.txt", 3, 8, 16)
    lying = grab(dg / "lying.txt", 1, 24, 16, HEADER)[0]
    ball = grab(dg / "ball.txt", 1, 16, 16, HEADER)[0]
    boots = grab(dg / "boots.txt", 1, 8, 8, HEADER)[0]
    hat = grab(dg / "hat.txt", 1, 8, 8, HEADER)[0]
    plate = grab(dg / "plate.txt", 1, 8, 8, HEADER)[0]
    arc = grab(dg / "arc.txt", 1, 8, 16, HEADER)[0]
    crate = grab(dg / "crate.txt", 1, 16, 16, HEADER)[0]
    saucer = grab(dg / "saucer.txt", 1, 16, 16, HEADER)[0]
    beam = grab(dg / "beam.txt", 2, 8, 16, HEADER)
    cooler = grab(dg / "cooler.txt", 2, 16, 16, HEADER)
    soda = grab(dg / "soda.txt", 4, 8, 16, HEADER)
    arrays = {
        # set A, OBJ 56..87: dust 3 x 2, ball 4, lying 6, upright 8, reaching 8 (offsets DG_* in src/dgag.c)
        "dg_a": sum((tile_bytes(f, 0, 0) + tile_bytes(f, 0, 8) for f in dust), []) + entries(ball, 16) + entries(lying, 24)
                + bartender_layout(dregs[0]) + bartender_layout(dregs[5]),
        "dg_boots": pair(boots), "dg_hat": pair(hat), "dg_plate": pair(plate),
        "dg_arc": tile_bytes(arc, 0, 0) + tile_bytes(arc, 0, 8),
        "dg_crate": entries(crate, 16), "dg_saucer": entries(saucer, 16),
        "dg_beam": sum((tile_bytes(f, 0, 0) + tile_bytes(f, 0, 8) for f in beam), []),
        "dg_monkey": entries(monkey[1], 16) + entries(monkey[2], 16),
        # the stadium's soda bath (POST_STADIUM page 2): OBJ T_B 4 tiles the upright cooler; OBJ T_X 12 tiles the tipped cooler (4), then the
        # stream, the sheet, the splash and the drips (2 each)
        "dg_cooler": entries(cooler[0], 16),
        "dg_soda": entries(cooler[1], 16) + sum((tile_bytes(f, 0, 0) + tile_bytes(f, 0, 8) for f in soda), []),
    }
    lines = ["// generated by tools/gen_dgag.py -- do not edit; #included by src/dgag.c",
             "#define DG_A_TILES %d" % (len(arrays["dg_a"]) // 16)]
    for k, v in arrays.items():
        lines.append("static const uint8_t %s[%d] = { %s };" % (k, len(v), ", ".join(f"0x{b:02X}" for b in v)))
    (outdir / "dgag_art.h").write_text("\n".join(lines) + "\n")
    (outdir / "dgag.json").write_text(json.dumps({k: v for k, v in arrays.items()}))
    sheet = [dregs[0], dregs[5], lying, ball, crate, saucer, monkey[1], monkey[2]] + \
            [list(b) + ["." * 8] * 8 for b in (boots, hat, plate)] + [arc] + beam + cooler + soda
    png(sheet, prev / "dgag_x8.png", 8, transparent=True)
    print("gen_dgag: set A %d tiles, props %d" % (len(arrays["dg_a"]) // 16, sum(len(v) for k, v in arrays.items() if k != "dg_a") // 16))


if __name__ == "__main__":
    main()
