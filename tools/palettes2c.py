#!/usr/bin/env python3
"""assets/palettes.json -> build/palettes.c + build/palettes.h

build/palettes.c is banked (`#pragma bank 255`, autobanked): the table is read only through pal_get() /
patron_pal_get(), BANKED functions in the same file, which copy one palette into the caller's (WRAM) buffer.

Each entry becomes a row of 4 RGB15 values {colour 0, index 1, index 2, index 3}.
Colour 0 is written as 0 (black): sprites never draw it, and for BG palettes the
game picks the colour 0 itself (the wall colour). Usage: palettes2c.py in.json outdir
"""
import json
import sys
from pathlib import Path

src, outdir = Path(sys.argv[1]), Path(sys.argv[2])
data = json.loads(src.read_text())
keys = [k for k in data if not k.startswith("_")]

h = ["// generated by tools/palettes2c.py from assets/palettes.json -- do not edit",
     "#ifndef PALETTES_H", "#define PALETTES_H", "#include <gb/gb.h>", "#include <stdint.h>", "",
     "// one palette = 4 RGB15 values: colour 0, then indices 1..3 of the art",
     "// (colour 0 is 0 here; BG code sets it, sprites ignore it)",
     "typedef uint16_t palette_t[4];", ""]
c = ["// generated by tools/palettes2c.py from assets/palettes.json -- do not edit",
     "#pragma bank 255", '#include "palettes.h"', "",
     "static const palette_t palettes[PAL_COUNT] = {"]
for i, k in enumerate(keys):
    h.append(f"#define PAL_{k.upper()} {i}")
    r = data[k]["rgb15"]
    c.append(f"    {{0, {r[0]}, {r[1]}, {r[2]}}},  // {k} {' '.join(data[k]['hex'])}")
groups = ["cowboys", "sports", "lumberjacks", "chefs", "divers", "robots", "punks", "ninjas", "zoo", "aliens"]  # = gen_art.PATRON_GROUPS
ids = []
for g in groups:
    names = ["zoo_monkey", "zoo_panda", "zoo_hippo"] if g == "zoo" else [f"{g}_{v}" for v in "abc"]
    ids.append([keys.index(n) for n in names])
# M14a enhanced variants: <group>_x is the group's extra OBJ palette (CGB OBJ 4, the lifted column of its enhanced variant
# that no patron palette shows; tools/gen_art.py validates the art against it). 255: the group has none.
xids = [keys.index(f"{g}_x") if f"{g}_x" in keys else 255 for g in groups]
h += ["", "// patron palettes per group (same order as the art): PAL_* ids of variants A, B, C",
      f"#define PATRON_PAL_GROUPS {len(groups)}", "void patron_pal_get(uint8_t g, uint8_t v, uint16_t *dst) BANKED;   // dst[0..3] = palette of group g's variant v",
      "// M14a: per group the PAL_* id of its extra OBJ palette <group>_x (255: none); an initializer for src/enhance.c's bank",
      "#define PATRON_X_IDS { " + ", ".join(map(str, xids)) + " }"]
c += []
h += ["", f"#define PAL_COUNT {len(keys)}", "// the table is in a switchable bank: copy one palette (4 RGB15 values) into dst (WRAM)",
      "void pal_get(uint8_t id, uint16_t *dst) BANKED;", "", "#endif", ""]
c += ["};", "", "static const uint8_t patron_pal_ids[PATRON_PAL_GROUPS][3] = {"]
c += [f"    {{{a}, {b}, {d}}},  // {g}" for (a, b, d), g in zip(ids, groups)]
c += ["};", "",
      "void pal_get(uint8_t id, uint16_t *dst) BANKED {",
      "    const uint16_t *s = palettes[id];",
      "    dst[0] = s[0]; dst[1] = s[1]; dst[2] = s[2]; dst[3] = s[3];",
      "}", "",
      "void patron_pal_get(uint8_t g, uint8_t v, uint16_t *dst) BANKED {",
      "    pal_get(patron_pal_ids[g][v], dst);",
      "}", ""]
outdir.mkdir(parents=True, exist_ok=True)
(outdir / "palettes.h").write_text("\n".join(h))
(outdir / "palettes.c").write_text("\n".join(c))
