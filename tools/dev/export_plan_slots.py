#!/usr/bin/env python3
"""Export the Graphics Atlas's slot plan as data: tools/artifacts/palette_plan/plan_slots.json.

  export_plan_slots.py [capture dir] [out json]

The Atlas (tools/artifacts/palette_plan/build.py) works out, per venue, which patrons and other things sit on each OBJ 0-7 and BG 0-7 palette and
in which colours (model() and field_model(): the plan applied to what the game has). The game's generators (tools/gen_art.py, tools/gen_looks.py)
read the JSON this writes and nothing else: no slot, colour or combination of the plan is typed in a generator.

build.py runs the Atlas's own self-check at import and needs a CAPTURE of the game as it was BEFORE the import (the page compares the plan with what
the game has): `make atlas` on a baseline build writes out/atlas/data. Without a capture the committed JSON is the record
(tests/test_plan_slots.py checks the game against it; with a capture it also checks the JSON against a fresh export).
"""
import contextlib
import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
PLAN = os.path.join(ROOT, "tools/artifacts/palette_plan")
DEFAULT_OUT = os.path.join(PLAN, "plan_slots.json")


def export(data_dir):
    """The slot plan of every venue from a capture directory (the Atlas's build.py imported with it)."""
    sys.argv = ["build.py", data_dir, os.path.join(ROOT, "out", "plan_slots_page.html")]
    os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
    sys.path.insert(0, PLAN)
    with contextlib.redirect_stdout(io.StringIO()):
        import build as B
    out = {}
    for v in B.venues:
        m = B.model(v)
        f = B.field_model(v, m)

        def entry(d):
            return dict(patrons=[x[0] for x in d["pat"]], other=[x[0] for x in d["oth"]], cols=[c.upper() for c in B.eff(d)],
                        match=str(d.get("match") or ""))
        keg = next((sl for sl in range(8) if any(x[0].startswith("Keg") for x in f[sl]["oth"])), None)
        body = next((sl for sl in range(8) if any(x[0] == "Boss body" for x in f[sl]["oth"])), None)
        out[v["key"]] = dict(name=v["name"], above=v["above"], field=v["field"], keg_bg=keg, boss_body_bg=body,
                             obj={str(sl): entry(m[("OBJ", sl)]) for sl in range(8)},
                             bg={str(sl): entry(f[sl]) for sl in range(8)})
    return out


if __name__ == "__main__":
    data = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "out/atlas/data")
    dst = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT
    d = export(data)
    with open(dst, "w") as fh:
        json.dump(dict(note="generated by tools/dev/export_plan_slots.py from the Graphics Atlas (plan_data.py + build.py model / field_model); do not edit",
                       venues=d), fh, indent=1, sort_keys=True)
        fh.write("\n")
    print("wrote", dst, len(d), "venues")
