#!/usr/bin/env python3
"""The scene transition's fizzy-drink tiles (owner idea 2026-10-15) -> build/trans_art.h (src/trans.c's bank), build/trans.json (tests)
and x8 previews in out/preview/ (greys, and in the HUD palette's colours as CGB shows them).

  assets/art/fizz.txt   9 tiles 8x8: FOAM, FILL, BUB1 shimmer A / B / POP, BUB2 shimmer A / B / POP, CREAM
Usage: gen_trans.py outdir previewdir
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_art import blocks, png, tile_bytes  # noqa: E402
from PIL import Image  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
HUD = [(0xF8, 0xE8, 0xB0), (0xC0, 0xA0, 0x50), (0xE8, 0xA0, 0x20), (0x18, 0x10, 0x40)]   # main_cold.c BG 1 (RGB15 -> 8 bit)


def main():
    outdir, prev = Path(sys.argv[1]), Path(sys.argv[2])
    fr = [r for _, r in blocks(ROOT / "assets/art/fizz.txt")]
    if len(fr) != 9 or not all(len(f) == 8 and all(len(r) == 8 and set(r) <= set(".-+#") for r in f) for f in fr):
        sys.exit("gen_trans: assets/art/fizz.txt needs 9 tiles of 8x8 in . - + #")
    data = []
    for f in fr:
        data += tile_bytes(f, 0, 0)
    lines = ["// generated by tools/gen_trans.py from assets/art/fizz.txt -- do not edit; #included by src/trans.c",
             "#define FZ_FOAM 0      // tile order: FOAM, FILL, then the bubbles' frames (FZ_BUB + 3 k + {0 A, 1 B, 2 POP}, k = 0, 1)",
             "#define FZ_FILL 1", "#define FZ_BUB 2", "#define FZ_CREAM 8      // all cream: the screen whitens (the LCD-off blank is white) and darkens again",
             f"static const uint8_t fz_tiles[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines += ["};", ""]
    (outdir / "trans_art.h").write_text("\n".join(lines))
    (outdir / "trans.json").write_text(json.dumps({"tiles": data}))
    png(fr, prev / "fizz_x8.png", 8)
    im = Image.new("RGB", (9 * 9, 8))
    for k, f in enumerate(fr):
        for y, r in enumerate(f):
            for x, c in enumerate(r):
                im.putpixel((k * 9 + x, y), HUD[".-+#".index(c)])
    im.resize((im.width * 8, im.height * 8), Image.NEAREST).save(prev / "fizz_hud_x8.png")


if __name__ == "__main__":
    main()
