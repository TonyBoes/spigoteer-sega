#!/usr/bin/env python3
"""The one-line menus' shared BG tiles: assets/art/ol_tiles.txt (23 tiles) then assets/art/ol_icons.txt (the 4 channel icons) -> BUILD/ol_tiles.h.

Usage: gen_ol_tiles.py BUILD_DIR. Both files are hand-placed pixel grids (8 rows of 8 characters, tiles separated by blank lines, ';' comments):
'.' colour 0, '-' 1, '+' 2, '#' 3. This script only transcribes them to 2 bpp; it decides no pixel. Tile n is BG id OL_T + n (src/oneline.h).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
N_TILES, N_ICONS = 23, 4


def grids(name, n):
    rows = [ln.strip() for ln in (ROOT / "assets" / "art" / name).read_text().splitlines() if ln.strip() and not ln.startswith(";")]
    assert len(rows) == 8 * n and all(len(r) == 8 and set(r) <= set(".-+#") for r in rows), f"{name}: {n} tiles of 8 rows of 8 pixels expected"
    return [rows[i:i + 8] for i in range(0, 8 * n, 8)]


def encode(tile):
    out = []
    for row in tile:
        lo = hi = 0
        for ch in row:
            v = ".-+#".index(ch)
            lo, hi = (lo << 1) | (v & 1), (hi << 1) | (v >> 1)
        out += [lo, hi]
    return out


def main():
    tiles = grids("ol_tiles.txt", N_TILES) + grids("ol_icons.txt", N_ICONS)
    data = [b for t in tiles for b in encode(t)]
    out = Path(sys.argv[1]) / "ol_tiles.h"
    out.write_text("// generated by tools/gen_ol_tiles.py from assets/art/ol_tiles.txt and ol_icons.txt -- do not edit\n"
                   f"#define OL_N {len(tiles)}\n"
                   "static const uint8_t ol_tiles[OL_N * 16] = {\n" + ",".join(map(str, data)) + "\n};\n")


if __name__ == "__main__":
    main()
