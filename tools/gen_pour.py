#!/usr/bin/env python3
"""Perfect pour art (story mode) -> build/pour_art.h (#included by src/pour.c, its bank), build/pour.json (tests) and
x8 previews in out/preview/.

  assets/art/pour/<t>.txt   per venue (gen_art THEMES order): 2 frames 8x16, SPARKLE then OVERFLOW, drawn over the
                            venue's full drink in his hand (assets/approved/venues/<t>_drink.txt frame 6) in that
                            drink's full palette. Swapping the art = editing these files; nothing else changes.
  assets/art/pour_cue.txt   the PERFECT cue at the catch: 1 frame 8x16.

VRAM: OBJ_POUR (234) .. +5 = sparkle (2 tiles), overflow (2), cue (2): above the patron BG tiles (78..233, OBJ ids >= 128
share VRAM with them) and below the DMG copies (OBJ_DMG_COPY 240..245). src/pour.c pour_load() writes them at a story
shift's start (LCD off); arcade never loads them.
Usage: gen_pour.py outdir previewdir
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_art import THEMES, blocks, obj_tiles, png  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OBJ_POUR = 234
POUR_TILES = 6


def frames(path, n):
    fr = [r for _, r in blocks(path)]
    if len(fr) != n or not all(len(f) == 16 and all(len(r) == 8 and set(r) <= set(".-+#") for r in f) for f in fr):
        sys.exit(f"gen_pour: {path.relative_to(ROOT)}: needs {n} frame(s) of 8x16 in . - + #")
    return fr


def main():
    outdir, prev = Path(sys.argv[1]), Path(sys.argv[2])
    outdir.mkdir(parents=True, exist_ok=True); prev.mkdir(parents=True, exist_ok=True)
    cue = frames(ROOT / "assets/art/pour_cue.txt", 1)
    cue_t = obj_tiles(cue, 8)
    h = ["// generated by tools/gen_pour.py from assets/art/pour/*.txt, assets/art/pour_cue.txt -- do not edit",
         "// per venue: sparkle (2 tiles) + overflow (2 tiles), 8x16 entries; then the cue (2 tiles)",
         f"static const uint8_t pour_venue_tiles[{len(THEMES)}][64] = {{"]
    info = {"obj_pour": OBJ_POUR, "venues": {}, "cue": cue_t}
    drinkdir = ROOT / "assets/approved/venues"
    for t in THEMES:
        fr = frames(ROOT / f"assets/art/pour/{t}.txt", 2)
        d = obj_tiles(fr, 8)
        h.append("    { " + ", ".join(f"0x{b:02X}" for b in d) + " },   // " + t)
        info["venues"][t] = d
        full = [r for _, r in blocks(drinkdir / f"{t}_drink.txt")][5]
        png([full] + fr + cue, prev / f"pour_{t}_x8.png", 8, transparent=True)
    h += ["};", f"static const uint8_t pour_cue_tiles[32] = {{ " + ", ".join(f"0x{b:02X}" for b in cue_t) + " };", ""]
    (outdir / "pour_art.h").write_text("\n".join(h))
    (outdir / "pour.json").write_text(json.dumps(info))


if __name__ == "__main__":
    main()
