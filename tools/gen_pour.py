#!/usr/bin/env python3
"""Perfect pour art (story mode) -> build/pour_art.h (#included by src/pour.c, its bank), build/pour.json (tests) and
x8 previews in out/preview/.

  assets/art/pour/<t>.txt   per venue (gen_art THEMES order): 2 frames 8x16, SPARKLE then OVERFLOW, drawn over the
                            venue's full drink in his hand (assets/approved/venues/<t>_drink.txt frame 6) in that
                            drink's full palette. Swapping the art = editing these files; nothing else changes.
  assets/art/pour_cue.txt   the PERFECT cue at the catch: 1 frame 8x16 (the x2 badge in its lower half).

VRAM: OBJ_POUR (40) .. +5 = sparkle (2 tiles), overflow (2), cue (2): sprite-only ids 40..45, between Sal's pictures and the mugs (Q61; they used to take the shared ids 234..239). src/pour.c pour_load() writes them at a story
shift's start (LCD off); arcade never loads them.
Usage: gen_pour.py outdir previewdir
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_art import THEMES, blocks, obj_tiles, png  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OBJ_POUR = 40
OBJ_POUR_CUE = OBJ_POUR + 4
CUE_TILES = 2
OBJ_DUST = 46      # the dust puff of a bar change (3 frames x 2 tiles; src/game.h OBJ_DUST: sprite-only 46..51)
DUST_FRAMES = 3


def frames(path, widths):
    fr = [r for _, r in blocks(path)]
    if len(fr) != len(widths) or not all(len(f) == 16 and all(len(r) == w and set(r) <= set(".-+#") for r in f)
                                         for f, w in zip(fr, widths)):
        sys.exit(f"gen_pour: {path.relative_to(ROOT)}: needs frames of " + ", ".join(f"{w}x16" for w in widths)
                 + " in . - + #")
    return fr


def main():
    outdir, prev = Path(sys.argv[1]), Path(sys.argv[2])
    outdir.mkdir(parents=True, exist_ok=True); prev.mkdir(parents=True, exist_ok=True)
    cue = frames(ROOT / "assets/art/pour_cue.txt", (8,))
    cue_t = obj_tiles(cue, 8)
    assert len(cue_t) == CUE_TILES * 16
    dust = frames(ROOT / "assets/art/dust.txt", (8, 8, 8))
    dust_t = obj_tiles(dust, 8)
    assert len(dust_t) == DUST_FRAMES * 32
    h = ["// generated by tools/gen_pour.py from assets/art/pour/*.txt, assets/art/pour_cue.txt -- do not edit",
         "// per venue: sparkle (2 tiles) + overflow (2 tiles), 8x16 entries; then the cue (2 tiles)",
         f"static const uint8_t pour_venue_tiles[{len(THEMES)}][64] = {{"]
    info = {"obj_dust": OBJ_DUST, "dust": dust_t, "obj_pour": OBJ_POUR, "obj_pour_cue": OBJ_POUR_CUE, "venues": {}, "cue": cue_t, "cue_art": cue}
    drinkdir = ROOT / "assets/approved/venues"
    for t in THEMES:
        fr = frames(ROOT / f"assets/art/pour/{t}.txt", (8, 8))
        d = obj_tiles(fr, 8)
        h.append("    { " + ", ".join(f"0x{b:02X}" for b in d) + " },   // " + t)
        info["venues"][t] = d
        full = [r for _, r in blocks(drinkdir / f"{t}_drink.txt")][5]
        png([full] + fr, prev / f"pour_{t}_x8.png", 8, transparent=True)
    png(cue, prev / "pour_cue_x8.png", 8, transparent=True)
    png(dust, prev / "dust_x8.png", 8, transparent=True)
    h += ["};", f"static const uint8_t dust_tiles[{len(dust_t)}] = {{ " + ", ".join(f"0x{b:02X}" for b in dust_t) + " };",
          f"static const uint8_t pour_cue_tiles[{len(cue_t)}] = {{ " + ", ".join(f"0x{b:02X}" for b in cue_t) + " };", ""]
    (outdir / "pour_art.h").write_text("\n".join(h))
    (outdir / "pour.json").write_text(json.dumps(info))


if __name__ == "__main__":
    main()
