#!/usr/bin/env python3
"""The Boss Rush list's portraits (src/rush.c): each boss's fight sprite, centred in the list's window by what is DRAWN -> BUILD/rush_portraits.h.

Usage: gen_rush_portraits.py BUILD_DIR (after tools/gen_boss.py: it reads BUILD/boss_<name>_art.h).
The window's backdrop is 6 x 4 tiles (48 x 32 px) and the body, pose 0 (WALK), fills its two middle tile rows (16 px). For each boss this writes 12 BG tiles,
6 columns x 2 rows (tile 2 * column + row): his body shifted right by whole pixels so that the middle of his drawn pixels (colour index not 0, from his leftmost
to his rightmost drawn pixel) falls on the middle of the 48 px; vertically the drawn rows must already be within half a pixel of the middle of the 16
(asserted). Nothing but a position is decided here: every pixel is the boss's own, from assets/art/boss/*.txt. Also the DMG's "??" for a locked boss, from the
story font's hand-drawn question mark (assets/tiles/story.txt, @glyph_quest), its drawn pixels in colour 3, centred the same way, and each boss's three
colours for the Color silhouette-or-colour palette.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOSSES = ["big_tex", "mascot", "sasquatch", "critic", "yeti", "prototype", "duke", "sumo", "leo", "mothership"]   # venue order (src/rush.c boss_name)
WIN_COLS = 6                                    # tile columns of the backdrop
MID_X = WIN_COLS * 8 // 2                       # 24
H = 16


def body_pixels(build, name):
    """Pose 0 of boss `name` as 16 rows of pixel indices (8 * columns wide), and his three colours (RGB15)."""
    text = (build / f"boss_{name}_art.h").read_text()
    cols = int(re.search(r"#define BOSS_ART_COLS (\d+)", text).group(1))
    body = [int(x, 16) for x in re.search(r"boss_art_body\[\d+\] = \{([^}]*)\}", text).group(1).replace("\n", " ").split(",") if x.strip()]
    pose0 = [int(x) for x in re.search(r"boss_art_pose\[[^\]]*\]\[[^\]]*\] = \{ \{([^}]*)\}", text).group(1).split(",")][:cols]
    pal = [int(x, 16) for x in re.search(r"boss_art_pal\[4\] = \{([^}]*)\}", text).group(1).split(",")]
    assert len(pose0) == cols
    rows = [[0] * (8 * cols) for _ in range(H)]
    for c, p in enumerate(pose0):
        for t in range(2):                      # the pair's top and bottom tile
            base = (2 * p + t) * 16
            for y in range(8):
                lo, hi = body[base + 2 * y], body[base + 2 * y + 1]
                for x in range(8):
                    rows[8 * t + y][8 * c + x] = ((lo >> (7 - x)) & 1) | (((hi >> (7 - x)) & 1) << 1)
    return rows, pal[1:4]


def quest_pixels():
    """The "??" as 16 rows of indices: the font's question mark twice, drawn pixels in colour 3, its rows centred on the 16."""
    lines = (ROOT / "assets" / "tiles" / "story.txt").read_text().splitlines()
    i = lines.index("@glyph_quest")
    g = [ln.strip() for ln in lines[i + 1:i + 9]]
    assert len(g) == 8 and all(len(r) == 8 for r in g)
    drawn = [[0 if ch == "#" else 3 for ch in r] for r in g]
    ys = [y for y, r in enumerate(drawn) if any(r)]
    oy = 8 - (ys[0] + ys[-1] + 1) // 2
    rows = [[0] * 16 for _ in range(H)]
    for y, r in enumerate(drawn):
        rows[y + oy][0:8] = r
        rows[y + oy][8:16] = r
    return rows


def centre(rows):
    """Shift right so the drawn box's middle is MID_X; returns the pixel rows (48 wide) and the centre errors (x, y) in px."""
    xs = [x for r in rows for x, v in enumerate(r) if v]
    ys = [y for y, r in enumerate(rows) if any(r)]
    x0, x1, y0, y1 = min(xs), max(xs), ys[0], ys[-1]
    dx = MID_X - (x0 + x1 + 1) // 2
    assert dx >= 0 and x1 + dx < WIN_COLS * 8, (dx, x0, x1)
    out = [[0] * (WIN_COLS * 8) for _ in range(H)]
    for y, r in enumerate(rows):
        for x, v in enumerate(r):
            out[y][x + dx] = v
    return out, abs((x0 + x1 + 1) / 2 + dx - MID_X), abs((y0 + y1 + 1) / 2 - H / 2)


def tiles(rows):
    """12 tiles, tile 2 * column + row, 16 bytes each (two bitplane bytes a pixel row)."""
    data = []
    for c in range(WIN_COLS):
        for t in range(2):
            for y in range(8):
                lo = hi = 0
                for x in range(8):
                    v = rows[8 * t + y][8 * c + x]
                    lo, hi = (lo << 1) | (v & 1), (hi << 1) | (v >> 1)
                data += [lo, hi]
    return data


def array(name, data, per=16):
    return f"static const uint8_t {name} = {{\n" + ",\n".join(", ".join(str(b) for b in data[i:i + per]) for i in range(0, len(data), per)) + "\n};\n"


def main():
    build = Path(sys.argv[1])
    out = ["// generated by tools/gen_rush_portraits.py from the boss art headers and assets/tiles/story.txt -- do not edit; #included by src/rush.c only (its bank)",
           "// rush_body[v]: boss v's 12 window tiles (6 columns x 2 rows, tile 2 * column + row), his drawn pixels centred on the window; rush_quest: the DMG's \"??\" the same way;",
           "// rush_colour[v]: his colours 1-3 (RGB15)", f"#define RUSH_PORTRAITS {len(BOSSES)}"]
    body, colour, worst = [], [], 0.0
    for name in BOSSES:
        rows, pal = body_pixels(build, name)
        shifted, ex, ey = centre(rows)
        assert ex <= 0.5 and ey <= 0.5, (name, ex, ey)
        worst = max(worst, ex, ey)
        body += tiles(shifted)
        colour += pal
    q, ex, ey = centre(quest_pixels())
    assert ex <= 0.5 and ey <= 0.5, ("quest", ex, ey)
    out.append(array(f"rush_body[{len(BOSSES)} * 192]", body, 24))
    out.append(array("rush_quest[192]", tiles(q), 24))
    out.append(f"static const uint16_t rush_colour[{len(BOSSES)} * 3] = {{ " + ", ".join(str(c) for c in colour) + " };\n")
    (build / "rush_portraits.h").write_text("\n".join(out))
    print(f"rush_portraits.h: {len(BOSSES)} bosses, worst centring error {worst} px")


if __name__ == "__main__":
    main()
