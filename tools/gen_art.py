#!/usr/bin/env python3
"""ASCII art -> GBDK tile data (build/art.c, build/art.h) + x8 previews.

  bar.txt        BG tileset: '@name' blocks, cut into 8x8 tiles row-major.
  bartender.txt  7 frames 16x24 -> per frame 4 OAM entries of 8x16 (2 columns x
                 2 rows; the bottom row is 8 px of art + 8 px transparent pad),
                 8 tiles per frame: [c0 top, c0 top-low, c1 top, c1 top-low,
                 c0 bot, pad, c1 bot, pad].
  mug.txt        2 frames 8x16 = 2 tiles each.
  mug_fill.txt   4 frames 8x16 (empty, 1/3, 2/3, full) = 2 tiles each.
  mug_drink.txt  4 frames 8x16 (upright full, tilted full, tilted emptying, upright empty) = 2 tiles each.
  patrons/*.txt  3 variants 16x16 per group -> build/patrons.c (own ROM bank): each variant pre-shifted
                 right by 0/2/4/6 px inside a 24x16 footprint (3x2 tiles, colour 0 background).
Usage: gen_art.py outdir previewdir
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PATRON_GROUPS = ["cowboys", "sports", "lumberjacks", "chefs", "divers", "robots", "ninjas", "aliens", "zoo"]
PATRON_SHIFTS = 4
IDX = {".": 0, "-": 1, "+": 2, "#": 3, "0": 0, "1": 1, "2": 2, "3": 3}
GREY = [(255, 255, 255), (170, 170, 170), (85, 85, 85), (0, 0, 0)]


def blocks(path, named=False):
    """Parse blocks of pixel rows separated by blank lines. Returns [(name, rows)]."""
    res, cur, name = [], [], None
    for line in path.read_text().splitlines() + [""]:
        line = line.rstrip()
        if line.startswith(("//",)) or (line.startswith(";")):
            continue
        if named and line.startswith("@"):
            if cur:
                res.append((name, cur)); cur = []
            name = line[1:]
            continue
        if line == "":
            if cur:
                res.append((name, cur)); cur = []
                if not named:
                    name = None
            continue
        cur.append(line)
    return res


def tile_bytes(rows, x0, y0):
    out = []
    for y in range(8):
        lo = hi = 0
        for x in range(8):
            v = IDX[rows[y0 + y][x0 + x]]
            lo |= (v & 1) << (7 - x)
            hi |= (v >> 1) << (7 - x)
        out += [lo, hi]
    return out


def fmt(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    return f"const uint8_t {name}[{len(data)}] = {{\n" + "\n".join(lines) + "\n};\n"


def png(rows_list, path, scale, transparent=False):
    """rows_list: list of frames (each a list of row strings) laid left to right."""
    h = max(len(f) for f in rows_list)
    w = sum(len(f[0]) + 1 for f in rows_list)
    im = Image.new("RGB", (w, h), (255, 0, 255) if transparent else (255, 255, 255))
    x0 = 0
    for f in rows_list:
        for y, r in enumerate(f):
            for x, c in enumerate(r):
                if transparent and c == ".":
                    im.putpixel((x0 + x, y), (200, 230, 255))
                else:
                    im.putpixel((x0 + x, y), GREY[IDX[c]])
        x0 += len(f[0]) + 1
    im.resize((w * scale, h * scale), Image.NEAREST).save(path)


def main():
    outdir, prev = Path(sys.argv[1]), Path(sys.argv[2])
    outdir.mkdir(parents=True, exist_ok=True); prev.mkdir(parents=True, exist_ok=True)
    c = ["// generated by tools/gen_art.py -- do not edit", '#include "art.h"', ""]
    h = ["// generated by tools/gen_art.py -- do not edit", "#ifndef ART_H", "#define ART_H",
         "#include <stdint.h>", ""]

    # ---- BG tileset ----
    bg, tiles, names = blocks(ROOT / "assets/tiles/bar.txt", named=True), [], []
    for name, rows in bg:
        assert len({len(r) for r in rows}) == 1, f"{name}: ragged rows"
        W, H = len(rows[0]), len(rows)
        assert W % 8 == 0 and H % 8 == 0, f"{name}: not a multiple of 8x8"
        h.append(f"#define TILE_{name.upper()} {len(tiles) // 16}")
        for ty in range(H // 8):
            for tx in range(W // 8):
                tiles += tile_bytes(rows, tx * 8, ty * 8)
    n = len(tiles) // 16
    assert n <= 256
    h += [f"#define BAR_TILE_COUNT {n}", "extern const uint8_t bar_tiles[];", ""]
    c.append(fmt("bar_tiles", tiles))
    # preview: tiles in a grid of 16 per row
    cols = 16
    im = Image.new("RGB", (cols * 9, ((n + cols - 1) // cols) * 9), (255, 0, 255))
    for t in range(n):
        for y in range(8):
            lo, hi = tiles[t * 16 + y * 2], tiles[t * 16 + y * 2 + 1]
            for x in range(8):
                v = ((lo >> (7 - x)) & 1) | (((hi >> (7 - x)) & 1) << 1)
                im.putpixel(((t % cols) * 9 + x, (t // cols) * 9 + y), GREY[v])
    im.resize((im.width * 8, im.height * 8), Image.NEAREST).save(prev / "bar_tiles_x8.png")

    # ---- bartender ----
    frames = [r for _, r in blocks(ROOT / "assets/art/bartender.txt")]
    assert len(frames) == 7 and all(len(f) == 24 and len(f[0]) == 16 for f in frames)
    bt, padded = [], []
    blank = ["." * 8] * 8
    for f in frames:
        pad = [r for r in f] + ["." * 16] * 8          # 16x32 with transparent pad
        padded.append(pad)
        for ty in (0, 16):                              # top entry row, bottom entry row
            for cx in (0, 8):
                bt += tile_bytes(pad, cx, ty) + tile_bytes(pad, cx, ty + 8)
        # reorder: entries must be c0top, c1top, c0bot, c1bot -> already (ty outer, cx inner)
    h += ["#define BARTENDER_FRAMES 7", "#define BARTENDER_TILES_PER_FRAME 8",
          f"#define BARTENDER_TILE_COUNT {len(bt) // 16}", "extern const uint8_t bartender_tiles[];", ""]
    c.append(fmt("bartender_tiles", bt))
    png(padded, prev / "bartender_x8.png", 8, transparent=True)

    # ---- mug ----
    mugs = [r for _, r in blocks(ROOT / "assets/art/mug.txt")]
    assert len(mugs) == 2 and all(len(f) == 16 and len(f[0]) == 8 for f in mugs)
    mt = []
    for f in mugs:
        mt += tile_bytes(f, 0, 0) + tile_bytes(f, 0, 8)
    h += ["#define MUG_FRAMES 2", f"#define MUG_TILE_COUNT {len(mt) // 16}",
          "extern const uint8_t mug_tiles[];", "", "#endif", ""]
    c.append(fmt("mug_tiles", mt))
    png(mugs, prev / "mug_x8.png", 8, transparent=True)

    # ---- mug_fill: 4 frames 8x16 (empty, 1/3, 2/3, full) = 2 tiles each ----
    fills = [r for _, r in blocks(ROOT / "assets/art/mug_fill.txt")]
    assert len(fills) == 4 and all(len(f) == 16 and len(f[0]) == 8 for f in fills)
    ft = []
    for f in fills:
        ft += tile_bytes(f, 0, 0) + tile_bytes(f, 0, 8)
    h[-2:-2] = ["#define MUG_FILL_FRAMES 4", f"#define MUG_FILL_TILE_COUNT {len(ft) // 16}",
                "extern const uint8_t mug_fill_tiles[];", ""]
    c.append(fmt("mug_fill_tiles", ft))
    png(fills, prev / "mug_fill_x8.png", 8, transparent=True)

    # ---- glass (breaking mug): 4 frames 16x16 = 2 OAM entries of 8x16 each ----
    glass = [r for _, r in blocks(ROOT / "assets/art/glass.txt")]
    assert len(glass) == 4 and all(len(f) == 16 and len(f[0]) == 16 for f in glass)
    gt = []
    for f in glass:
        for cx in (0, 8):
            gt += tile_bytes(f, cx, 0) + tile_bytes(f, cx, 8)
    h[-2:-2] = ["#define GLASS_FRAMES 4", "#define GLASS_TILES_PER_FRAME 4",
                f"#define GLASS_TILE_COUNT {len(gt) // 16}", "extern const uint8_t glass_tiles[];", ""]
    c.append(fmt("glass_tiles", gt))
    png(glass, prev / "glass_x8.png", 8, transparent=True)

    # ---- mug_drink: 4 frames 8x16 = 2 tiles each ----
    drinks = [r for _, r in blocks(ROOT / "assets/art/mug_drink.txt")]
    assert len(drinks) == 4 and all(len(f) == 16 and len(f[0]) == 8 for f in drinks)
    dt = []
    for f in drinks:
        dt += tile_bytes(f, 0, 0) + tile_bytes(f, 0, 8)
    h[-2:-2] = ["#define MUG_DRINK_FRAMES 4", f"#define MUG_DRINK_TILE_COUNT {len(dt) // 16}",
                "extern const uint8_t mug_drink_tiles[];", ""]
    c.append(fmt("mug_drink_tiles", dt))
    png(drinks, prev / "mug_drink_x8.png", 8, transparent=True)

    # ---- coin (tip): 8x8 art in the lower half of an 8x16 entry; frame 1 swaps the two body shades (glint) ----
    coin = [r for _, r in blocks(ROOT / "assets/art/coin.txt")][0]
    assert len(coin) == 8 and len(coin[0]) == 8
    swap = str.maketrans("-+", "+-")
    coin_frames = [["." * 8] * 8 + coin, ["." * 8] * 8 + [r.translate(swap) for r in coin]]
    ct = []
    for f in coin_frames:
        ct += tile_bytes(f, 0, 0) + tile_bytes(f, 0, 8)
    h[-2:-2] = ["#define COIN_FRAMES 2", f"#define COIN_TILE_COUNT {len(ct) // 16}",
                "extern const uint8_t coin_tiles[];", ""]
    c.append(fmt("coin_tiles", ct))
    png(coin_frames, prev / "coin_x8.png", 8, transparent=True)

    # ---- dancer (stage show): 4 frames 16x24, laid out like the bartender (8 tiles per frame) ----
    dframes = [r for _, r in blocks(ROOT / "assets/art/dancer.txt")]
    assert len(dframes) >= 3 and all(len(f) == 24 and len(f[0]) == 16 for f in dframes)
    dt = []
    for f in dframes:
        pad = list(f) + ["." * 16] * 8
        for ty in (0, 16):
            for cx in (0, 8):
                dt += tile_bytes(pad, cx, ty) + tile_bytes(pad, cx, ty + 8)
    h[-2:-2] = [f"#define DANCER_FRAMES {len(dframes)}", "#define DANCER_TILES_PER_FRAME 8",
                f"#define DANCER_TILE_COUNT {len(dt) // 16}", "extern const uint8_t dancer_tiles[];", ""]
    c.append(fmt("dancer_tiles", dt))
    png(dframes, prev / "dancer_x8.png", 8, transparent=True)

    # ---- patrons: 9 groups x 3 variants x 4 shifts x (3x2 tiles, row-major) ----
    # The 16x16 patron is pasted at x offset 0/2/4/6 into a 24x16 canvas of colour 0 (the wall colour in
    # the patron palettes), so a patron moves in 2 px steps by swapping tilemap entries only.
    pc = ["// generated by tools/gen_art.py -- do not edit", "#include <gb/gb.h>", '#include "art.h"',
          "#pragma bank 255", "BANKREF(patron_tiles)", ""]
    pt = []
    for g in PATRON_GROUPS:
        vs = [r for _, r in blocks(ROOT / f"assets/art/patrons/{g}.txt")]
        assert len(vs) == 3 and all(len(v) == 16 and len(v[0]) == 16 for v in vs), g
        shifted_rows = []
        for v in vs:
            for s in range(PATRON_SHIFTS):
                canvas = ["." * 24 for _ in range(16)]
                for y in range(16):
                    canvas[y] = "." * (2 * s) + v[y] + "." * (24 - 16 - 2 * s)
                for ty in (0, 8):
                    for tx in (0, 8, 16):
                        pt += tile_bytes(canvas, tx, ty)
                shifted_rows.append(canvas)
        png([r for _, r in blocks(ROOT / f"assets/art/patrons/{g}.txt")], prev / f"patrons_{g}_x8.png", 8)
        if g == PATRON_GROUPS[0]:
            png(shifted_rows[:PATRON_SHIFTS], prev / "patrons_shifted_x8.png", 8)
    per_group = 3 * PATRON_SHIFTS * 6
    assert len(pt) == len(PATRON_GROUPS) * per_group * 16
    h[-2:-2] = [f"#define PATRON_GROUPS {len(PATRON_GROUPS)}",
                f"#define PATRON_SHIFTS {PATRON_SHIFTS}",
                f"#define PATRON_TILES_PER_GROUP {per_group}   // 3 variants x 4 shifts x 6 tiles (3x2)",
                f"#define PATRON_GROUP_BYTES {per_group * 16}",
                "// tile of (variant v, shift s, row r, column k): v * 24 + s * 6 + r * 3 + k",
                "// group order: " + ", ".join(PATRON_GROUPS),
                "extern const uint8_t patron_tiles[];   // in its own ROM bank: BANKREF_EXTERN(patron_tiles)", ""]
    pc.append(fmt("patron_tiles", pt))
    (outdir / "patrons.c").write_text("\n".join(pc))

    (outdir / "art.h").write_text("\n".join(h))
    (outdir / "art.c").write_text("\n".join(c))


main()
