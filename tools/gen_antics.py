#!/usr/bin/env python3
"""CLASSIC's end-of-level antics art (owner-approved 2026-10-11) -> build/antics_art.h (src/antics.c's bank),
build/antics.json (tests) and x8 previews in out/preview/.

  assets/art/antics/antics.txt     4 bartender poses, 16x24 (bartender.txt's layout): KICK, HOP, DAZED, DRINK
  assets/art/antics/antics_fx.txt  4 frames 8x16: the dove flying (wings up, wings down), stunned; the stars

32 OBJ tiles in 8x16 entries (loaded over the show's tiles, OBJ_DANCER, while the level is clear):
  KICK 0-7 and HOP 8-15 (TL, TR, BL, BR entries as a bartender frame), DAZED's top entries 16-19 (its bottom is
  bartender_idle's), DRINK's top entries 20-23 (its bottom is bartender_fail's), the dove 24-29 (3 entries), the stars
  30-31. The reused bottoms are checked pixel for pixel here.
Usage: gen_antics.py outdir previewdir
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_art import blocks, png, tile_bytes  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "assets/art/antics"
BT_IDLE, BT_FAIL = 0, 6


def frames(path, n, w, h):
    fr = [r for _, r in blocks(path)]
    if len(fr) != n or not all(len(f) == h and all(len(r) == w and set(r) <= set(".-+#") for r in f) for f in fr):
        sys.exit(f"gen_antics: {path.relative_to(ROOT)}: needs {n} frames of {w}x{h} in . - + #")
    return fr


def entries(f, rows):
    """8x16 entries of a 16-wide frame (padded to 32 rows), the entry rows given (0 top, 16 bottom), left then right."""
    f = f + ["." * len(f[0])] * (32 - len(f))
    out = []
    for ey in rows:
        for ex in (0, 8):
            out += tile_bytes(f, ex, ey) + tile_bytes(f, ex, ey + 8)
    return out


def main():
    outdir, prev = Path(sys.argv[1]), Path(sys.argv[2])
    kick, hop, dazed, drink = frames(ART / "antics.txt", 4, 16, 24)
    fx = frames(ART / "antics_fx.txt", 4, 8, 16)
    bt = [r for _, r in blocks(ROOT / "assets/art/bartender.txt")]
    for name, f, src in (("DAZED", dazed, BT_IDLE), ("DRINK", drink, BT_FAIL)):
        if f[16:] != bt[src][16:]:
            sys.exit(f"gen_antics: antics.txt {name}: rows 16-23 must be bartender frame {src}'s (its bottom entries are reused)")
    data = entries(kick, (0, 16)) + entries(hop, (0, 16)) + entries(dazed, (0,)) + entries(drink, (0,))
    for f in fx:
        data += tile_bytes(f, 0, 0) + tile_bytes(f, 0, 8)
    assert len(data) == 32 * 16
    lines = ["// generated by tools/gen_antics.py from assets/art/antics/*.txt -- do not edit; #included by src/antics.c",
             "#define ANT_TILES 32      // loaded at OBJ_DANCER while the level is clear",
             "#define ANT_KICK 0        // TL, TR, BL, BR entries", "#define ANT_HOP 8",
             "#define ANT_DAZED 16      // top entries; the bottom is bartender_idle's",
             "#define ANT_DRINK 20      // top entries; the bottom is bartender_fail's",
             "#define ANT_BIRD_UP 24", "#define ANT_BIRD_DOWN 26", "#define ANT_BIRD_STUN 28", "#define ANT_STARS 30",
             f"static const uint8_t ant_tiles[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines += ["};", ""]
    (outdir / "antics_art.h").write_text("\n".join(lines))
    (outdir / "antics.json").write_text(json.dumps({"tiles": data}))
    png([kick, hop, dazed, drink], prev / "antics_poses_x8.png", 8, transparent=True)
    png(fx, prev / "antics_fx_x8.png", 8, transparent=True)


if __name__ == "__main__":
    main()
