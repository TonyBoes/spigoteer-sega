#!/usr/bin/env python3
"""Leo's roar and entrance sprites -> build/leo_fx_art.h (src/boss_leo.c only), build/leo_fx.json (tests), a preview.

  assets/art/leo_fx.txt          ARC1, ARC2 (8x16), HOOP_A, HOOP_B (16x32)
  assets/art/boss/leo.txt        @ROAR (32x16): drawn as sprites for the entrance's leap (LEAP)

Every frame is cut into 8x16 OBJ cells; equal cells (and X mirrored ones) share a tile pair. The pairs go to OBJ tiles from
LEO_FX_OBJ (a fight's free ids: OBJ 96-103 are the topper's frames, the show's other ids are not used in a fight).
Usage: gen_leo_fx.py outdir previewdir
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_art import blocks, png, tile_bytes  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OBJ_BASE = 104
OBJ_MAX = 128
FRAMES = [("LEAP", 32, 16), ("ARC1", 8, 16), ("ARC2", 8, 16), ("HOOP_A", 16, 32), ("HOOP_B", 16, 32)]


def main():
    outdir, prev = Path(sys.argv[1]), Path(sys.argv[2])
    outdir.mkdir(parents=True, exist_ok=True)
    prev.mkdir(parents=True, exist_ok=True)
    fx = dict(blocks(ROOT / "assets/art/leo_fx.txt", named=True))
    leo = dict(blocks(ROOT / "assets/art/boss/leo.txt", named=True))
    named = dict(fx)
    named["LEAP"] = leo["ROAR"]
    pairs, index, cells, first, shown = [], {}, [], [0], []
    for n, w, h in FRAMES:
        f = named[n]
        if len(f) != h or not all(len(r) == w and set(r) <= set(".-+#") for r in f):
            sys.exit(f"gen_leo_fx: @{n} must be {w}x{h} in . - + #")
        shown.append(f)
        for y in range(0, h, 16):
            for x in range(0, w, 8):
                k = tuple(f[y + j][x:x + 8] for j in range(16))
                if all(set(r) == {"."} for r in k):
                    continue
                m = tuple(r[::-1] for r in k)
                if k in index:
                    p, fl = index[k], 0
                elif m in index:
                    p, fl = index[m], 1
                else:
                    p, fl = len(pairs), 0
                    index[k] = p
                    pairs.append(tile_bytes(f, x, y) + tile_bytes(f, x, y + 8))
                cells.append((x, y, OBJ_BASE + 2 * p, 0x20 if fl else 0))
        first.append(len(cells))
    if OBJ_BASE + 2 * len(pairs) > OBJ_MAX:
        sys.exit(f"gen_leo_fx: {len(pairs)} tile pairs do not fit OBJ {OBJ_BASE}-{OBJ_MAX - 1}")
    png(shown, prev / "leo_fx_x8.png", 8, transparent=True)
    flat = [b for p in pairs for b in p]
    h = ["// generated by tools/gen_leo_fx.py from assets/art/leo_fx.txt -- do not edit; #included by src/boss_leo.c",
         f"#define LEO_FX_OBJ {OBJ_BASE}",
         f"#define LEO_FX_TILES {2 * len(pairs)}   // 8x16 pairs at OBJ {OBJ_BASE}..",
         "static const uint8_t leo_fx_tiles[%d] = { %s };" % (len(flat), ", ".join(f"0x{b:02X}" for b in flat))]
    h += [f"#define FX_{n} {i}" for i, (n, _, _) in enumerate(FRAMES)]
    h += ["static const uint8_t leo_fx_first[%d] = { %s };" % (len(first), ", ".join(map(str, first))),
          "static const uint8_t leo_fx_cells[%d] = { %s };   // per cell: dx, dy, OBJ tile id, S_FLIPX when mirrored" % (
              4 * len(cells), ", ".join(str(v) for c in cells for v in c))]
    (outdir / "leo_fx_art.h").write_text("\n".join(h) + "\n")
    (outdir / "leo_fx.json").write_text(json.dumps({"base": OBJ_BASE, "pairs": [list(p) for p in pairs],
                                                    "frames": {n: [list(c) for c in cells[first[i]:first[i + 1]]]
                                                               for i, (n, _, _) in enumerate(FRAMES)}}))


if __name__ == "__main__":
    main()
