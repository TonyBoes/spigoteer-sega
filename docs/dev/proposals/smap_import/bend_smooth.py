def aa_pass(rows, mode):
    """Q115 anti-aliasing test: the staircase of each kerb edge gets a mid shade (letter m = body index 1: on DMG the mid grey between ground 0 and kerb 2, on Color the road's peach) at its
    step corners, using only the colours already in the palette.  Mode 1: a ground pixel with kerb to its east and south (outer arc) or to its west and north (inner arc) turns m.
    Mode 2: also a kerb pixel with ground to its west and north (outer) or east and south (inner) turns m."""
    R = len(rows)
    g = [list(r) for r in rows]
    at = lambda x, y: rows[y][x] if 0 <= x < R and 0 <= y < R else "?"
    for y in range(R):
        for x in range(R):
            c = rows[y][x]
            if c == "g" and ((at(x + 1, y) == "k" and at(x, y + 1) == "k") or (at(x - 1, y) == "k" and at(x, y - 1) == "k")):
                g[y][x] = "m"
            elif mode == 2 and c == "k" and ((at(x - 1, y) == "g" and at(x, y - 1) == "g") or (at(x + 1, y) == "g" and at(x, y + 1) == "g")):
                g[y][x] = "m"
    return ["".join(r) for r in g]


