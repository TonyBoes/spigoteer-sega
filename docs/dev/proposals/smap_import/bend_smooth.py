def _at(lst, j):
    return lst[j] if j < len(lst) else 0


def grid(R):
    """the R x R picture (rows of letters g k l b o) of the NW bend of outer radius R"""
    o, i = OUT[R], IN[R]
    rows = []
    for y in range(R):
        g, gk, gkl = o["g"][y], o["gk"][y], o["gkl"][y]
        j = R - 1 - y
        G, GK, GKL = _at(i["G"], j), _at(i["GK"], j), _at(i["GKL"], j)
        row = []
        for x in range(R):
            if x < g:
                c = "g"
            elif x < gk:
                c = "k"
            elif x < gkl:
                c = "l"
            elif x >= R - G and G:
                c = "g"
            elif x >= R - GK and GK:
                c = "k"
            elif x >= R - GKL and GKL:
                c = "l"
            else:
                c = "b"
            row.append(c)
        rows.append(row)
    for (x, y) in (SPECKS[R] if R in SPECKS else polar_specks(R)):
        if rows[y][x] == "b" and all(rows[y + dy][x + dx] in "bo" for dx in (-1, 0, 1) for dy in (-1, 0, 1) if 0 <= x + dx < R and 0 <= y + dy < R):
            rows[y][x] = "o"
    if AA:
        rows = aa_pass(rows, AA)
    return ["".join(r) for r in rows]


