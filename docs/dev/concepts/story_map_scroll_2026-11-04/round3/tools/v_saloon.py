"""The Saloon, 72 x 56 (9 x 7 cells). Palette SALOON: 0 sand, 1 lit timber, 2 timber shade, 3 ink. Light from the top left.
A false-front timber saloon: the sign, stepped front, two floors, an awning, batwing doors, a hitching post, two barrels."""
from canvas import Canvas, piece
from art import R

W, H = 72, 56
PAL = "saloon"

# ---- pieces -----------------------------------------------------------------------------------------------------------
WIN8 = piece("3:8", ("3:1 0:3 2:1 0:2 3:1", 4), "3:1 2:6 3:1", ("3:1 0:3 2:1 0:2 3:1", 4), "3:8", "1:8")
WIN12 = piece("3:12", ("3:1 0:4 2:2 0:4 3:1", 3), "3:1 2:10 3:1", ("3:1 0:4 2:2 0:4 3:1", 3), "3:12", "1:12")
WIN12S = piece("3:12", ("3:1 0:4 2:2 0:4 3:1", 2), "3:1 2:10 3:1", ("3:1 0:4 2:2 0:4 3:1", 2), "3:12", "1:12")   # ground floor, 8 high with the sill
# batwing doors: the frame, the dark room behind, the two short swinging doors with their slats
DOOR = piece("2:12", ("3:12", 3),
             "3:1 2:10 3:1",
             "3:1 1:4 2:2 1:4 3:1", "3:1 2:4 3:2 2:4 3:1",
             "3:1 1:4 2:2 1:4 3:1", "3:1 2:4 3:2 2:4 3:1",
             "3:1 1:4 2:2 1:4 3:1", "3:1 2:10 3:1",
             ("3:12", 2))
POST = piece("3:1 1:1 3:1", ("3:1 1:1 3:1", 5))
BARREL = piece(".:1 3:7 .:1",
               "3:1 1:3 1:1 2:3 3:1",
               "3:9",
               "3:1 1:4 2:3 3:1", "3:1 1:3 3:1 2:1 2:2 3:1",
               "3:1 1:2 3:3 2:2 3:1", "3:1 1:3 3:1 2:1 2:2 3:1",
               "3:1 1:4 2:3 3:1",
               "3:9",
               "3:1 1:4 2:3 3:1", "3:1 1:4 2:3 3:1",
               ".:1 3:7 .:1")


def build():
    c = Canvas("saloon", PAL, W, H)
    # ---- the sign and the stepped front ------------------------------------------------------------------------------
    c.row(0, "0:20 3:32 0:20")
    c.row(1, "0:20 3:1 2:30 3:1 0:20")
    for y in (2, 3, 4):
        c.row(y, "0:20 3:1 2:1 1:28 2:1 3:1 0:20")
    letters = [  # T A P S, 3 x 5, ink on the gold board (the game's sign: TAPS)
        "333" "1" "131" "1" "333" "1" "333",
        "131" "1" "313" "1" "313" "1" "311",
        "131" "1" "333" "1" "333" "1" "333",
        "131" "1" "313" "1" "311" "1" "113",
        "131" "1" "313" "1" "311" "1" "333"]
    for k, L in enumerate(letters):
        assert len(L) == 15
        c.row(5 + k, "0:20 3:1 2:1 1:7 =" + L + " 1:6 2:1 3:1 0:20")
    c.row(10, "0:6 3:15 2:1 1:28 2:1 3:15 0:6")
    c.row(11, "0:6 3:1 1:13 3:1 2:1 1:28 2:1 3:1 1:13 3:1 0:6")
    c.row(12, "0:6 3:1 3:13 3:1 2:30 3:1 3:13 3:1 0:6")
    PL13 = "(1:3 2:1)*3 1:1"
    PL30 = "(1:3 2:1)*7 1:2"
    # upper floor: planks, two windows, a double window over the door
    for y in range(13, 28):
        c.row(y, f"0:6 3:1 {PL13} 3:1 {PL30} 3:1 {PL13} 3:1 0:6")
    c.paste(9, 16, WIN8)
    c.paste(55, 16, WIN8)
    c.paste(30, 16, WIN12)
    # ---- the awning ---------------------------------------------------------------------------------------------------
    c.row(28, "0:4 3:64 0:4")
    c.row(29, "0:4 3:1 1:62 3:1 0:4")
    c.row(30, "0:4 3:1 (2:5 3:1)*10 2:2 3:1 0:4")
    c.row(31, "0:4 3:1 (2:5 3:1)*10 2:2 3:1 0:4")
    c.row(32, "0:4 3:64 0:4")
    for y in (33, 34):
        c.row(y, "0:6 3:1 2:58 3:1 0:6")
    # ---- ground floor -------------------------------------------------------------------------------------------------
    for y in range(35, 47):
        c.row(y, "0:6 3:1 (1:3 2:1)*14 1:2 3:1 0:6")
    c.row(47, "0:6 3:60 0:6")
    c.paste(8, 35, piece(("3:1 1:1 3:1", 12)))
    c.paste(61, 35, piece(("3:1 1:1 3:1", 12)))
    c.paste(14, 37, WIN12S)
    c.paste(46, 37, WIN12S)
    c.paste(30, 35, DOOR)
    # ---- boardwalk ----------------------------------------------------------------------------------------------------
    c.row(48, "0:2 1:68 0:2")
    c.row(49, "0:2 (2:8 3:1)*7 2:5 0:2")
    c.row(50, "0:2 3:68 0:2")
    c.row(51, "0:4 1:64 0:4")
    # ---- the hitching post, left front ---------------------------------------------------------------------------------
    c.paste(6, 44, piece(("3:1 1:1 3:1", 12)))
    c.paste(26, 44, piece(("3:1 1:1 3:1", 12)))
    c.paste(9, 45, piece("3:17", "1:17", "3:17"))
    # two barrels, right front
    c.paste(58, 41, BARREL)
    c.paste(47, 43, BARREL)
    return c


if __name__ == "__main__":
    rows = build()
    print(len(rows), len(rows[0]))
