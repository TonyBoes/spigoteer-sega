"""Hand-drawn pixels for the scrolling story map (concept 2026-11-04).

Every grid below is typed by hand: a digit is the colour index (0-3) inside the cell's BG palette, '.' is index 0 (the
building's own ground).  Long rows are written as runs joined with + so a 48-px frieze is not 48 typed characters.
Scripts (world.py, render.py) only cut these grids into 8x8 cells, place them and convert.

BG palettes (index = palette * 4 + colour); see world.PAL:
  0 snow / fog      1 sand / roads   2 grass       3 wood / fence
  4 TOWN (new, replaces the teal one)   5 fountain / gold   6 stadium + air base   7 blue (factory, cow, pond)
"""


def chk(rows, w, h, name):
    assert len(rows) == h, f"{name}: {len(rows)} rows, wanted {h}"
    for i, r in enumerate(rows):
        assert len(r) == w, f"{name} row {i}: {len(r)} wide, wanted {w}: {r!r}"
    return rows


