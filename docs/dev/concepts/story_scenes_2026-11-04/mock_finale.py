ORDER = ['SADIE', 'COACH', 'JUNE', 'COLBY', 'AURORA', 'MGRBOT', 'GRANNY', 'HANA', 'KIKI', 'ZIZZ']
DROP = {'COACH': 1, 'AURORA': 1, 'GRANNY': 2, 'HANA': 1}      # shorter figures stand lower

# the INTRO's cobble tile, rows 88-103 (8 wide): '#' mortar, 'm' stone, 'g' highlight
COBBLE = ['########', 'gggmmmm#', 'mmmmmmm#', 'mmmmmmm#', 'mmmmmmm#', 'mmmmmmm#',
          '########', 'ggg#mmmm', 'mmm#mmmm', 'mmm#mmmm', 'mmm#mmmm', 'mmm#mmmm',
          '########', 'gggmmmm#', 'mmmmmmm#', 'mmmmmmm#']
RECOL = {'#': 'm', 'm': 'p', 'g': 'g'}    # mortar -> the fountain stone (shade 2), stone -> plaza (shade 1), highlight stays


def main():
    lines = SRC.read_text().split('\n')
    k = lines.index('@key')
    pix = lines.index('@pixels')
    keys = lines[k + 1:pix]
    keys.insert(1, '. 0 #d0ecf8 sky')
    keys = [l for i, l in enumerate(keys) if not (i > 1 and l.startswith('. 0'))]
    keys += ['G 1 #f0b888 window glass by day (sunlit; the only free shade-1 colour in the town palette)', 'p 1 #f0b888 plaza cobble (sandstone, the skin colour)']
    rows = [list(r) for r in lines[pix + 1:pix + 105]]
    assert len(rows) == 104 and all(len(r) == 160 for r in rows)
    # windows: the town's glass (x 0-47, rows 57-87); the clock face above stays light
    for y in range(57, 88):
        for x in range(48):
            if rows[y][x] == 'g':
                rows[y][x] = 'G'
    # the plaza, rows 88-103: row 88 its ink edge, then the cobbles
    for y in range(88, 104):
        for x in range(160):
            c = COBBLE[y - 88][x % 8]
            rows[y][x] = '#' if y == 88 else RECOL[c]
    # the crowd
    for i, name in enumerate(ORDER):
        g = FIG[name].strip('\n').split('\n')
        assert len(g) == 14 and all(len(r) == 16 for r in g), name
        d = DROP.get(name, 0)
        for r in range(14 - d):
            for x, c in enumerate(g[r]):
                if c == '#':
                    rows[90 + d + r][i * 16 + x] = '#'
        if d:   # the dropped rows' shoulders stay a full band at the bottom
            for r in range(14 - d, 14):
                for x, c in enumerate(g[r]):
                    if c == '#':
                        rows[90 + r][i * 16 + x] = '#'
    # clean-up pass, by hand (each pixel decided from the lint's orphan list, see the log in AUDIT/PLAN)
    CLEAN = {(7, 89): 'p', (39, 89): 'p', (55, 89): 'p', (151, 89): 'p',     # mortar stubs on a head top -> stone
             (14, 93): 'm', (32, 95): 'p',                                   # trapped stone / highlight -> mortar / stone
             (108, 94): '#', (139, 98): '#',                                 # Granny's knot, Kiki's hair flick joined to the head
             (58, 98): '#', (90, 98): '#', (91, 98): '#', (122, 99): '#', (35, 99): '#', (132, 98): '#',   # necks widened by 1
             (0, 100): '#', (63, 100): '#', (80, 100): '#', (16, 101): '#', (30, 101): '#',
             (110, 101): '#', (112, 101): '#',                               # cobble slivers in the shoulder band -> band
             (58, 86): '.', (58, 87): '.', (60, 87): '.'}                    # the old Colby head's toque tip above the plaza -> sky
    for (x, y), c in CLEAN.items():
        rows[y][x] = c
    head = [l for l in lines[:k]]
    head[0] = ('; FINALE (MOCKUP 2026-11-04, scratch tree only): the square by day; the ten owners as a crowd of silhouettes on the '
               'plaza (as the INTRO crowd), the plaza under the fountain, glass in the town windows.')
    out = head + ['@key'] + keys + ['@pixels'] + [''.join(r) for r in rows] + lines[pix + 105:]
    DST.write_text('\n'.join(out))
    print('wrote', DST)


main()
