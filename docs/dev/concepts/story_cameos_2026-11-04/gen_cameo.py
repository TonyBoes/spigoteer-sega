"""Story cameo mockup: transcribe the figures into 8x16 OBJ tiles for the scratch ROM. Transcription only (no pixel is decided here):
the bosses' poses are read from assets/art/boss/sasquatch.txt and leo.txt, the valve from assets/story/pictures/intro_pieces.txt,
the UFO from assets/story_map/obj_ufo.png, the beam from beam.txt (hand-placed, this folder). Tiles that are identical, or
identical mirrored left-right, are stored once (the entry gets the hardware X flip).
Usage: python3 gen_cameo.py TREE   -> writes TREE/src/cameo_art.h and prints the tile counts."""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
T = sys.argv[1]
KEY = {'.': 0, '-': 1, '+': 2, '#': 3}


def block(path, name, w):
    lines = open(path).read().split('\n')
    i = lines.index('@' + name)
    rows = lines[i + 1:i + 17]
    assert all(len(r) == w for r in rows), (name, [len(r) for r in rows])
    return [[KEY[c] for c in r] for r in rows]


def valve():
    lines = open(os.path.join(T, 'assets/story/pictures/intro_pieces.txt')).read().split('\n')
    i = [k for k, l in enumerate(lines) if l.startswith('@piece valve')][0]
    rows = []
    for l in lines[i + 1:]:
        if not l.strip():
            break
        rows.append([{'.': 0, 'Y': 1, 'y': 2, '#': 3}[c] for c in l])
    return rows


def ufo():
    im = Image.open(os.path.join(T, 'assets/story_map/obj_ufo.png'))
    px = im.load()
    return [[px[x, y] for x in range(im.size[0])] for y in range(im.size[1])]


def beam():
    rows = [l for l in open(os.path.join(HERE, 'beam.txt')).read().split('\n') if l and not l.startswith(';')]
    assert len(rows) == 40 and all(len(r) == 24 for r in rows)
    return [[KEY[c] for c in r] for r in rows]


SQ = os.path.join(T, 'assets/art/boss/sasquatch.txt')
LEO = os.path.join(T, 'assets/art/boss/leo.txt')
FIGS = {
    'sq_happy': block(SQ, 'HAPPY', 32), 'sq_duck': block(SQ, 'DUCK', 32), 'sq_hat': block(SQ, 'HAT_STILL', 8),
    'valve': valve(),
    'leo_walk': block(LEO, 'WALK', 32), 'leo_happy': block(LEO, 'HAPPY', 32), 'leo_hat': block(LEO, 'HAT_STILL', 8),
    'ufo': ufo(), 'beam': beam(),
}
SETS = [('lumber', 98, 30, ['sq_happy', 'sq_duck', 'sq_hat', 'valve']),
        ('zoo', 40, 16, ['leo_walk', 'leo_happy', 'leo_hat']),
        ('space', 98, 30, ['ufo', 'beam'])]


def strip(g, cx, by):
    """16 rows x 8 columns at column cx, band by: a tile pair (32 bytes), or None if empty."""
    data = []
    for y in range(by * 16, by * 16 + 16):
        lo = hi = 0
        for x in range(8):
            v = g[y][cx * 8 + x] if y < len(g) and cx * 8 + x < len(g[y]) else 0
            lo |= (v & 1) << (7 - x)
            hi |= ((v >> 1) & 1) << (7 - x)
        data += [lo, hi]
    return None if not any(data) else data


def flip(d):
    return [int('{:08b}'.format(b)[::-1], 2) for b in d]


out = ['// GENERATED by docs/dev/concepts/story_cameos_2026-11-04/gen_cameo.py (mockup, scratch tree only). Do not edit.',
       '#include <stdint.h>']
for name, base, cap, figs in SETS:
    tiles = []
    for f in figs:
        g = FIGS[f]
        w, h = max(len(r) for r in g), len(g)
        ents = []
        for by in range((h + 15) // 16):
            for cx in range((w + 7) // 8):
                d = strip(g, cx, by)
                if d is None:
                    continue
                if d in tiles:
                    k, fl = tiles.index(d), 0
                elif flip(d) in tiles:
                    k, fl = tiles.index(flip(d)), 1
                else:
                    tiles.append(d)
                    k, fl = len(tiles) - 1, 0
                ents += [cx * 8, by * 16, base + 2 * k, fl]
        out.append('static const uint8_t cf_%s[] = { %d, %s };' % (f, len(ents) // 4, ', '.join(map(str, ents))))
        print(name, f, '%dx%d' % (w, h), 'entries', len(ents) // 4)
    n = 2 * len(tiles)
    assert n <= cap, (name, n, cap)
    out.append('#define CAM_%s_BASE %d' % (name.upper(), base))
    out.append('#define CAM_%s_N %d' % (name.upper(), n))
    out.append('static const uint8_t cam_tiles_%s[] = { %s };' % (name, ', '.join('0x%02X' % b for d in tiles for b in d)))
    print(name, 'OBJ tiles', n, 'at', base, '-', base + n - 1)
open(os.path.join(T, 'src/cameo_art.h'), 'w').write('\n'.join(out) + '\n')
