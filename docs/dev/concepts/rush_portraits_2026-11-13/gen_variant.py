#!/usr/bin/env python3
"""PROPOSAL generator for the Boss Rush list's portraits (build flag RUSHPIC=A|B|C, see the Makefile): writes BUILD/rush_portraits.h.

    gen_variant.py BUILD A|B|C        (after tools/gen_boss.py; the default build never calls this)

A  the whole figure at 1:1 (the topper's upper half over the body's 16 rows = up to 24 rows), on three tile rows of the window; the tiles are packed by
   content: only the non-blank 8x8 tiles, shared between bosses, and a map of 6 x 4 window tiles per boss (+ one for the DMG "??"). Needs the matching
   code in src/rush.c (#ifdef RUSHPIC_A). Each boss is shifted by a whole number of pixels both ways; where (dx, dy) lands is decided here only by
   the picture's own bounding box and the VRAM budget (see choose_dy), never by editing a pixel.
B  option_b.txt: the artist's hand-drawn reductions (16 rows), centred like the full-size pictures; same output format as the shipped generator.
C  the same 16 rows as now but the window starts at the boss's own top (his topper's first drawn row) instead of at the body's top: head kept, the
   lowest rows lost. Per-boss start rows are the table C_START below, chosen by eye.
Nothing here draws or edits a pixel of any boss; B reads the artist's file.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import rp_common as c   # noqa: E402
import view_b           # noqa: E402

g = c.g
BOSSES = c.BOSSES
VRAM_IDS = 120            # src/rush.c: BG ids 136..255
QUEST_IDS = 4             # the "??" needs at most this many (counted below)
C_START = dict(big_tex=1, mascot=5, sasquatch=2, critic=6, yeti=1, prototype=2, duke=2, sumo=3, leo=2, mothership=4)   # first full-figure row of C's 16


def array(name, data, per=16, t="uint8_t"):
    return f"static const {t} {name} = {{\n" + ",\n".join(", ".join(str(b) for b in data[i:i + per]) for i in range(0, len(data), per)) + "\n};\n"


def common_head(what):
    return [f"// generated by docs/dev/concepts/rush_portraits_2026-11-13/gen_variant.py ({what}) from the boss art headers -- do not edit; #included by src/rush.c only"]


def place(rows, h_out, dx, dy, w_out=48):
    out = [[0] * w_out for _ in range(h_out)]
    for y, r in enumerate(rows):
        for x, v in enumerate(r):
            if v:
                out[y + dy][x + dx] = v
    return out


def fig_centre_dx(rows):
    x0, x1, _, _ = c.bbox(rows)
    return c.g.MID_X - (x0 + x1 + 1) // 2


def variant_bc(build, which):
    """B / C: the shipped format (12 tiles a boss, tile 2 * column + row), the body rows replaced."""
    out = common_head(f"option {which}") + [f"#define RUSH_PORTRAITS {len(BOSSES)}"]
    body, colour, worst = [], [], 0.0
    grids = view_b.load_b(HERE / "options_b.txt") if which == "B" else None
    for name in BOSSES:
        full, pal = c.full_boss(build, name)
        if which == "B":
            rows = [[".-+#".index(ch) for ch in r.ljust(max(len(x) for x in grids[name]), ".")] for r in grids[name]]
            assert len(rows) == 16, name
        else:
            s = C_START[name]
            rows = [list(r) for r in full[s:s + 16]]
        # centre by the drawn pixels, whole pixels, as the shipped generator does (x), and by the drawn rows (y) within the 16
        x0, x1, y0, y1 = c.bbox(rows)
        dx = g.MID_X - (x0 + x1 + 1) // 2
        dy = 8 - (y0 + y1 + 1) // 2 if which == "B" else 0
        grid = [[0] * 48 for _ in range(16)]
        for y, r in enumerate(rows):
            for x, v in enumerate(r):
                if v:
                    assert 0 <= y + dy < 16 and 0 <= x + dx < 48, (name, x, y, dx, dy)
                    grid[y + dy][x + dx] = v
        body += g.tiles(grid)
        colour += pal
        print(f"  {name:11s} option {which}: rows {y0}..{y1} dx {dx} dy {dy}")
    q, ex, ey = g.centre(g.quest_pixels())
    out.append(array(f"rush_body[{len(BOSSES)} * 192]", body, 24))
    out.append(array("rush_quest[192]", g.tiles(q), 24))
    out.append(array(f"rush_colour[{len(BOSSES)} * 3]", colour, 12, "uint16_t"))
    (build / "rush_portraits.h").write_text("\n".join(out))
    print(f"rush_portraits.h (option {which}): {len(BOSSES)} bosses")


def tiles_for(grid, rows_t):
    cells = []
    for ty in range(rows_t):
        for tx in range(6):
            t = c.tile_of(grid, tx, ty)
            cells.append(t if any(any(r) for r in t) else None)
    return cells


def choose_dy(figs, budget):
    """Per boss a vertical shift dy (0..8: the figure's 24 rows inside the window's 32) so that the picture is as near centred as the VRAM budget allows:
    minimise the total |dy - ideal| with the total of non-blank tiles (counted per boss, sharing ignored) <= budget. Pure bookkeeping on the bounding boxes."""
    opts = {}
    for n, (rows, dx) in figs.items():
        _, _, y0, y1 = c.bbox(rows)
        ideal = (32 - (y1 - y0 + 1)) // 2 - y0
        lst = []
        for dy in range(0, 9):
            grid = place(rows, 32, dx, dy)
            cells = [t for t in tiles_for(grid, 4) if t is not None]
            lst.append((abs(dy - ideal), dy, len(set(cells))))
        opts[n] = lst
    best = {0: (0, [])}                       # tiles used -> (cost, picks)
    for n in BOSSES:
        nxt = {}
        for used, (cost, picks) in best.items():
            for cst, dy, nt in opts[n]:
                u = used + nt
                if u > budget:
                    continue
                if u not in nxt or cost + cst < nxt[u][0]:
                    nxt[u] = (cost + cst, picks + [(n, dy)])
        best = nxt
    cost, picks = min(best.values(), key=lambda t: t[0])
    return dict(picks)


def variant_a(build, mode="centred"):
    figs, pals = {}, {}
    for n in BOSSES:
        rows, pal = c.full_boss(build, n)
        figs[n] = (rows, fig_centre_dx(rows))
        pals[n] = pal
    qrows = g.quest_pixels()
    qgrid, _, _ = g.centre(qrows)
    qfull = [[0] * 48 for _ in range(32)]
    for y in range(16):
        qfull[8 + y] = qgrid[y]                # the "??" on the two body rows of the four, as the list shows it today (window rows 2 and 3)
    if mode == "seated":
        dys = {n: 8 for n in BOSSES}
    elif mode == "top":
        dys = {n: 0 for n in BOSSES}
    else:
        dys = choose_dy(figs, VRAM_IDS - QUEST_IDS)
    uniq, order = {}, []
    maps = []
    for n in BOSSES + ["quest"]:
        if n == "quest":
            grid = qfull
        else:
            rows, dx = figs[n]
            grid = place(rows, 32, dx, dys[n])
        m = []
        for t in tiles_for(grid, 4):
            if t is None:
                m.append(0)
            else:
                if t not in uniq:
                    uniq[t] = len(uniq) + 1
                    order.append(t)
                m.append(uniq[t])
        maps.append(m)
    assert len(order) <= VRAM_IDS, (len(order), "unique tiles; the list has", VRAM_IDS, "ids")
    data = [b for t in order for b in c.tile_bytes(t)]
    out = common_head(f"option A, {mode}") + [f"#define RUSH_PORTRAITS {len(BOSSES)}", f"#define RUSH_TILE_N {len(order)}",
                                                   "#define RUSH_MAP_W 24   // 6 columns x 4 window rows a picture; entry RUSH_PORTRAITS is the DMG's \"??\""]
    out.append(array(f"rush_tiles[{len(order)} * 16]", data, 24))
    out.append(array(f"rush_map[{len(maps)} * 24]", [v for m in maps for v in m], 24))
    out.append(array(f"rush_colour[{len(BOSSES)} * 3]", [v for n in BOSSES for v in pals[n]], 12, "uint16_t"))
    (build / "rush_portraits.h").write_text("\n".join(out))
    print(f"rush_portraits.h (option A {mode}): {len(order)} unique tiles of {VRAM_IDS} ids; dy {dys}")


def main():
    build = Path(sys.argv[1])
    which = sys.argv[2]
    if which in ("B", "C"):
        variant_bc(build, which)
    elif which.startswith("A"):
        variant_a(build, {"A": "centred", "AS": "seated", "AT": "top"}[which])
    else:
        sys.exit("gen_variant: A, AS, AT, B or C")


if __name__ == "__main__":
    main()
