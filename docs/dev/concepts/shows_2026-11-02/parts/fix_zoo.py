p = 'parts/zoo_dance.txt'
L = open(p).read().split('\n')
f1 = ["....##++++##....",
      ".....#+#.#+#....",
      ".....#+...#+##..",
      ".....#+....#++#.",
      ".....#+.....###.",
      "....##+........."]
f3 = ["....##++++##....",
      ".....#+#.#+#....",
      "..##+#+..#+.....",
      ".#++#....#+.....",
      ".####....#+.....",
      ".........##....."]
# frame k starts at line index 25*k ; rows 17..22
for k, rows in ((1, f1), (3, f3)):
    for i, r in enumerate(rows):
        L[25 * k + 17 + i] = r
# F3 body: drop the stray left-edge pixels rows 15-17
for i in (15, 16, 17):
    L[75 + i] = L[75 + i].replace('#.#+++', '..#+++', 1) if i == 15 else L[75 + i]
L[75 + 16] = "...#++++++++###."
L[75 + 17] = "....##++++##...."
open(p, 'w').write('\n'.join(L))
